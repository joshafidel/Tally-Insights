-- Weigh ins recorded at plain state level get a county, sampled with
-- probability proportional to county population, deterministic per row.
with c as (
  select state, slug,
    sum(pop) over (partition by state order by slug rows between unbounded preceding and 1 preceding) as lo,
    sum(pop) over (partition by state order by slug) as hi,
    sum(pop) over (partition by state) as total
  from public.demo_counties
)
update public.weigh_ins w
set district_id = lower(c.state) || '-co-' || c.slug
from c
where length(w.district_id) = 2
  and w.district_id <> 'us'
  and upper(w.district_id) = c.state
  and (abs(hashtext(w.user_id::text || w.kind || w.item_id))::bigint % c.total) >= coalesce(c.lo, 0)
  and (abs(hashtext(w.user_id::text || w.kind || w.item_id))::bigint % c.total) < c.hi;
